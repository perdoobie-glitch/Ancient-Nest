import {generateKeyPairSync,randomBytes} from 'node:crypto';
import {mkdir,writeFile} from 'node:fs/promises';
const pair=generateKeyPairSync('rsa',{modulusLength:3072});
await mkdir('.secrets',{recursive:true,mode:0o700});
await writeFile('.secrets/account-signing-private.pem',pair.privateKey.export({format:'pem',type:'pkcs8'}),{mode:0o600,flag:'wx'});
await writeFile('.secrets/account-signing-public.pem',pair.publicKey.export({format:'pem',type:'spki'}),{mode:0o644,flag:'wx'});
await writeFile('.secrets/code-pepper.txt',randomBytes(32).toString('hex'),{mode:0o600,flag:'wx'});
await writeFile('.secrets/coordinator-api-key.txt',randomBytes(32).toString('hex'),{mode:0o600,flag:'wx'});
console.log('Created secret files in .secrets/. They were NOT printed. Back them up securely; never commit or share them.');
console.log('Do not regenerate or overwrite production secrets casually: key rotation invalidates active game assertions.');
